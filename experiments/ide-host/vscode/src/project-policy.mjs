// Project authority is determined by the source URI, never by a file name
// shown in a tree widget. This is an editor-side preflight; only a filesystem
// provider can enforce access against every native/external write path.
export const PROJECT_ROOT_DIRECTORIES=Object.freeze(["skills","lib","output"]);
const DIRECTORY_SET=new Set(PROJECT_ROOT_DIRECTORIES);

function parent(path){
  const i=path.lastIndexOf("/");
  return i>0?path.slice(0,i):"/";
}
function normalizedPath(uri){
  const path=uri?.path;
  if(typeof path!=="string"||!path.startsWith("/")||
     path.split("/").some(segment=>segment==="."||segment===".."||
       /%2e/i.test(segment)))return null;
  return path.replace(/\/+$/,"")||"/";
}
function sameAuthority(a,b){
  // An OPFS/browser URI and a local file URI must not authorize each other.
  return (a?.scheme??"")===(b?.scheme??"")&&
    (a?.authority??"")===(b?.authority??"");
}

export function projectRoots(workspaceFolders=[]){
  const roots=[];
  for(const folder of workspaceFolders??[]){
    const path=normalizedPath(folder?.uri);
    if(!path)continue;
    // Earlier Studio versions exposed the skills source as the Workspace.
    const root=path.endsWith("/skills")?parent(path):path;
    if(!roots.some(entry=>entry.path===root&&sameAuthority(entry.uri,folder.uri)))
      roots.push({path:root,uri:folder.uri});
  }
  return roots.sort((a,b)=>b.path.length-a.path.length);
}

export function classifyProjectResource(uri,workspaceFolders=[]){
  const path=normalizedPath(uri);
  if(!path)return {role:"invalid",readonly:true,protected:true};
  for(const root of projectRoots(workspaceFolders)){
    if(!sameAuthority(uri,root.uri))continue;
    if(path===root.path)
      return {role:"project-root",readonly:true,protected:true,projectRoot:root.path};
    if(!path.startsWith(root.path+"/"))continue;
    const relative=path.slice(root.path.length+1);
    const [top,...tail]=relative.split("/");
    if(!DIRECTORY_SET.has(top))
      return {role:"other",readonly:false,protected:false,projectRoot:root.path};
    const protectedRoot=tail.length===0;
    const readonly=top!=="skills"||protectedRoot;
    return {role:top,readonly,protected:protectedRoot,projectRoot:root.path};
  }
  return {role:"outside",readonly:false,protected:false};
}

export function checkStudioMutation(uri,workspaceFolders=[],operation="edit"){
  const entry=classifyProjectResource(uri,workspaceFolders);
  if(entry.role==="invalid")
    return {allowed:false,reason:"Invalid project resource URI",...entry};
  if(entry.protected)
    return {allowed:false,reason:"Project structure is managed by Skill Studio",...entry};
  if(entry.role==="lib")
    return {allowed:operation==="import-library",
      reason:"lib/ is managed, read-only Tool contract input",...entry};
  if(entry.role==="output")
    return {allowed:operation==="compiler-output",
      reason:"output/ is generated by the Skill Compiler, not editable Source",...entry};
  return {allowed:true,reason:null,...entry};
}

export function assertStudioMutation(uri,workspaceFolders=[],operation="edit"){
  const verdict=checkStudioMutation(uri,workspaceFolders,operation);
  if(!verdict.allowed)throw Error(
    "SKILL Studio: "+verdict.reason+" ("+(uri?.path??"unknown")+")");
  return verdict;
}
